// 카테고리 표준 정의 및 스마트 자동 추론 엔진

export const STANDARD_CATEGORIES = [
  '헤어/바디',
  '뷰티/스킨케어',
  '뷰티/메이크업',
  '덴탈/미백',
  '디지털/애플',
  '디지털/가전',
  '헬스/단백질',
  '식음료/음료',
  '간식/디저트',
  '캐릭터/완구',
  '홈/인테리어',
  '리빙/생활',
  '리빙/자취',
  '데스크테리어',
  '패션/잡화',
  '트렌드/핫템',
] as const;

export type StandardCategory = (typeof STANDARD_CATEGORIES)[number] | string;

/**
 * 상품명이나 쿼리 텍스트를 분석하여 가장 적합한 카테고리를 자동 추론합니다.
 */
export function inferCategory(nameOrQuery: string): string {
  if (!nameOrQuery) return '트렌드/핫템';

  const text = nameOrQuery.toLowerCase().replace(/[\s\-_/]/g, '');

  // 1. 헤어 / 바디 (미역, 트리트먼트, 샴푸 등)
  if (/미역|헤어|트리트먼트|샴푸|린스|에센스|모발|탈모|헤어팩|바디워시|바디로션|모레모|헤어오일|헤어세럼|컬링/.test(text)) {
    return '헤어/바디';
  }

  // 2. 덴탈 / 미백
  if (/치약|칫솔|치아|덴탈|오스템|뷰센|구강|가글|미백제|치간/.test(text)) {
    return '덴탈/미백';
  }

  // 3. 뷰티 / 메이크업
  if (/톤업|쿠션|파데|파운데이션|립스틱|틴트|마스카라|아이라이너|파우더|블러셔|코스노리|컨실러/.test(text)) {
    return '뷰티/메이크업';
  }

  // 4. 뷰티 / 스킨케어 (달바, 세럼, 크림, 코팩 등)
  if (/스킨|토너|로션|세럼|앰플|수분크림|보습|미백크림|선크림|선록|코팩|피지|블랙헤드|화이트헤드|마스크팩|달바|미팩토리|시카|클렌징|아이크림|물광/.test(text)) {
    return '뷰티/스킨케어';
  }

  // 5. 디지털 / 애플
  if (/아이폰|아이패드|맥북|에어팟|애플워치|아이맥|맥미니|apple|iphone|ipad|macbook|airpods/.test(text)) {
    return '디지털/애플';
  }

  // 6. 디지털 / 가전
  if (/이어폰|헤드폰|블루투스|충전기|모니터|키보드|마우스|스피커|샥즈|가전|청소기|로봇청소기|거치대/.test(text)) {
    return '디지털/가전';
  }

  // 7. 헬스 / 단백질
  if (/닭가슴살|프로틴|단백질|헬스|보충제|쉐이크|굽네|셀렉스|bcaa|크레아틴|다이어트식단/.test(text)) {
    return '헬스/단백질';
  }

  // 8. 식음료 / 음료
  if (/콜라|펩시|사이다|음료|탄산|커피|생수|주스|제로|티|에이드|밀크티|원두/.test(text)) {
    return '식음료/음료';
  }

  // 9. 간식 / 디저트
  if (/쿠키|초콜릿|두바이|두쫀쿠|카다이프|과자|빵|베이커리|디저트|간식|케이크|젤리|마카롱|떡/.test(text)) {
    return '간식/디저트';
  }

  // 10. 캐릭터 / 완구
  if (/인형|피규어|치이카와|먼작귀|하치와레|우사기|장난감|굿즈|완구|쿠션|봉제/.test(text)) {
    return '캐릭터/완구';
  }

  // 11. 홈 / 인테리어
  if (/크리스마스|트리|조명|전구|오너먼트|인테리어|디퓨저|캔들|가구|침구|러그/.test(text)) {
    return '홈/인테리어';
  }

  // 12. 리빙 / 텀블러 / 생활
  if (/텀블러|머그컵|보온병|콜드컵|스타벅스|수납|주방|자취|살림/.test(text)) {
    return '리빙/생활';
  }

  return '트렌드/핫템';
}
